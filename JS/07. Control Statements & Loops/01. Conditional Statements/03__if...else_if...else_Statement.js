// =============================================================== if...else if...else STATEMENT ===================================================================

// // SYNTAX
// if (condition) {
//     // runs if condition1 is true
// } else if (condition_2) {
//     // runs if condition_2 is true
// } else {
//     // runs if none are true
// }


// EXAMPLE
var marks = 75;

if (marks >= 90) {
    console.log("Grade A");
} else if (marks >= 75) {
    console.log("Grade B");                 // Grade B
} else if (marks >= 60) {
    console.log("Grade C");
} else {
    console.log("Fail");
}