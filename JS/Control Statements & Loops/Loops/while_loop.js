// ====================================================================== while LOOP ======================================================================


// SYNTAX

// // initialization
// while (condition) {
//     // Code to be executed
//     // Increment / Decrement
// }


// EXAMPLE

var i = 1;
while (i <= 5) {
    console.log(i);                 // 1 2 3 4 5
    i++;
}

var j = 5;
while (j >= 1) {
    console.log(j);                 // 5 4 3 2 1
    j--;
}