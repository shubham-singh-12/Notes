// ================================================================== CREATING AN ARRAY ==================================================================


// 1. Using ARRAY CONSTRUCTOR
let fruits_1 = new Array("apple", "Mango", "Grapes");

console.log(fruits_1);                    // [ 'apple', 'Mango', 'Grapes' ]
console.log(typeof (fruits_1));           // object




// ================================================================

// 2. Using ARRAY LITERALS
let fruits_2 = ["apple", "Mango", "Grapes"];

console.log(fruits_2);                  // [ 'apple', 'Mango', 'Grapes' ]
console.log(typeof (fruits_2));         // object





// ================================================================

// 3. We can also create an EMPTY ARRAY
let fruits_3 = [];

console.log(fruits_3);                  // []
console.log(typeof (fruits_3));         // object





// ================================================================

// 4. Array with Different Data types
let mixedArray = ["Shubham", 24, true, 20.5];

console.log(mixedArray);                    // [ 'Shubham', 24, true, 20.5 ]
console.log(typeof (mixedArray));           // object