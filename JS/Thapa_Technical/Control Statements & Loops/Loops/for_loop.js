// ======================================================================= for LOOP =======================================================================

// // SYNTAX

// for (start; condition; update) {
//     // Code block to be executed
// }

// start        --> Initialization
// condition    --> Condition
// Update       --> Increment / Decrement


// EXAMPLE
for (var i = 1; i <= 5; i++) {
    console.log(i);                 // 1 2 3 4 5
}

for (var j = 5; j >= 1; j--) {
    console.log(j);                 // 5 4 3 2 1
}