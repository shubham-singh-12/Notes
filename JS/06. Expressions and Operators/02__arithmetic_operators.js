// ================================================================= ARITHMETIC OPERATORS =================================================================

// Given that:
x = 5;
y = 2;


// Addition (+)
// Adds two values or variables.
console.log(x + y);                 // 7


// Subtraction (-)
// Subtracts the right operand from the left operand.
console.log(x - y);                 // 3


// Multiplication (*)
// Multiplies two values or variables.
console.log(x * y);                 // 10


// Division (/)
// Divides the left operand by the right operand.
console.log(x / y);                 // 2.5


// Modulus (Remainder)(%)
// Returns the remainder when the left operand is divided by the right operand.
console.log(x % y);                 // 1


// Exponential (**)
// Raises the first operand to the power of the second operand.
console.log(x ** y);                // 25


// Increment (++)
// The increment operator, increses number by 1.
x++;
var z = x;
console.log(z);                     // 6

++x;
var z = x;
console.log(z);                     // 6


// Decrement (--)
// The decrement operator, decreases number by 1.
y--
var z = y;
console.log(y);                     // 1

--y;
var z = y;
console.log(y);                     // 1