// ======================================================================== STRING ========================================================================
var userName = "Shubham";
let userName_1 = 'Shubham';

console.log(typeof userName);                   // string
console.log(typeof userName_1);                 // string
console.log();

// ========================================================================================================================================================
// ======================================================================== NUMBER ========================================================================
let number_1 = 10;
let number_2 = -10;
let number_3 = 10.99;

console.log(typeof number_1);                   // number
console.log(typeof number_2);                   // number
console.log(typeof number_3);                   // number
console.log();

// ========================================================================================================================================================
// ======================================================================== BigInt ========================================================================
let bigNumber = 102938475610293847561029384756;
let bigNumber_1 = 102938475610293847561029384756n;

console.log(typeof bigNumber);                      // number
