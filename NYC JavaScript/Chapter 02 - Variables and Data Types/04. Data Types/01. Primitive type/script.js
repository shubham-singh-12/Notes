// ========================================================================================================================================================
// ====================================================================== undefined =======================================================================
let a;
console.log(typeof a);                  // undefined
console.log();

// ========================================================================================================================================================
// ========================================================================= null =========================================================================
let b = null;

console.log(b);                 // null
console.log(typeof b);          // object
console.log();

// ========================================================================================================================================================
// ======================================================================== Symbol ========================================================================
let uniqueName = Symbol("name");

console.log(typeof uniqueName);                 // symbol
console.log();

// ========================================================================================================================================================
// ======================================================================== Boolean ========================================================================
let flag = true;
