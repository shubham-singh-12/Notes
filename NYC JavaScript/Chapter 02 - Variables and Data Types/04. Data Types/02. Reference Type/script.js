// ======================================================================== OBJECT ========================================================================
let userInfo = {
    name: "Shubham",
    age: 24,
    city: "Delhi",
    DOB: "17/10/2002"
}

console.log(typeof userInfo);           // object
console.log(userInfo);                  // { name: 'Shubham', age: 24, city: 'Delhi', DOB: '17/10/2002' }
console.log()

