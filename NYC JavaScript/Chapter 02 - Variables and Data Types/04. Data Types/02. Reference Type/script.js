// ======================================================================= FUNCTION =======================================================================
function greet() {
    console.log("Hey, how are u...");
};

greet();                    // Hey, how are u...
console.log();

// Parameters & Arguments
function sum(num_1, num_2) {
    console.log(num_1 + num_2);
}

sum(10, 20);                    // 30
sum(30, 40);                    // 70
sum(50, 60);                    // 110
console.log();

// return in Function
function product(number_1, number_2){
    return number_1 * number_2;
};

console.log(product(10, 11));                   // 110
console.log(product(12, 22));                   // 264
console.log(product(13, 33));                   // 429
console.log();

let result = product(2, 5);
console.log(result);                    // 10

