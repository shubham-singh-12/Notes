// ======================================================================== ARRAY =========================================================================
let a = [10, 20, 30, 40, 50, "Shubham", true, null, ["Aryan", 20], {}];

console.log(typeof a);              // object
console.log(a);                     // [ 10, 20, 30, 40, 50, 'Shubham', true, null, [ 'Aryan', 20 ], {} ]
console.log();

