// ================================================================= ARITHMETIC OPERATORS =================================================================

// ========================= Addition (+) =========================
console.log(2 + 2);                     // 4
console.log(2 + "2");                   // 22
console.log("Shu" + "bham");            // Shubham
console.log();

// ========================================================================================================================================================
// ======================= Subtraction (-) ========================
console.log(2 - 2);                 // 0
console.log(2 - "2");               // 0
console.log();

// ========================================================================================================================================================
// ====================== Multiplication (*) ======================
console.log(2 * 2);                 // 4
console.log();

// ========================================================================================================================================================
// ========================== Divide (/) ==========================
console.log(2 / 2);                 // 1
console.log(4 / 2);                 // 2
console.log();

// ========================================================================================================================================================
// ========================= Modulus (%) ==========================
console.log(4 % 2);                 // 0
console.log(5 % 2);                 // 1
console.log(14 % 3);                // 2
console.log();

// ========================================================================================================================================================
// ======================= Exponential (**) =======================
console.log(2 ** 3);                    // 8
console.log(2 ** 5);                    // 32
console.log();