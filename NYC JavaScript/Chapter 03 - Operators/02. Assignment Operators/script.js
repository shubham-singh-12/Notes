// ================================================================= ASSIGNMENT OPERATORS =================================================================

// ==================== Simple Assignment (=) =====================
let a = 10;

console.log(a);                 // 10
console.log();

// ========================================================================================================================================================
// =================== Addition Assignment (+=) ===================
a += 20;

console.log(a);                 // 30
console.log();

// ========================================================================================================================================================
// ================= Subtraction Assignment (-=) ==================
a -= 10;

console.log(a);                 // 20
console.log();

// ========================================================================================================================================================
// ================ Multiplication Assignment (*=) ================
a *= 2;

console.log(a);                 // 40
console.log();

// ========================================================================================================================================================
// =================== Division Assignment (/=) ===================
a /= 2;

console.log(a);                 // 20
console.log();

// ========================================================================================================================================================
// =================== Modulus Assignment (%=) ====================
a %= 5;

console.log(a);                 // 0
console.log();

// ========================================================================================================================================================
// ================= Exponential Assignment (**=) =================
let b = 2;
b **= 5;
console.log(b);                 // 32

console.log();