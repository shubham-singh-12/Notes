// ================================================================= COMPARISON OPERATORS =================================================================

let a = 12;
let b = 15;
let c = "12";

// ==================================================================== Equals to (==) ====================================================================
console.log(a == c);                    // true
console.log();

// ========================================================================================================================================================
// =============================================================== Strictly Equals to (===) ===============================================================
console.log(a === c);                   // false
console.log();

// ========================================================================================================================================================
// =================================================================== Not Equals (!=) ====================================================================
console.log(a != c);                    // false
console.log();

// ========================================================================================================================================================
// ============================================================== Strictly Not Equals (!==) ===============================================================
console.log(a != c);                    // false
console.log(a !== c);                   // true
console.log();

// ========================================================================================================================================================
// ============================================================= Greater than Equals to (>=) ==============================================================
console.log(a >= b);                    // false
console.log(b >= a);                    // true
console.log();

// ========================================================================================================================================================
// =============================================================== Less then Equals to (<=) ===============================================================
console.log(a <= b);                    // true
console.log(b <= a);                    // false
console.log();

// ========================================================================================================================================================
// =================================================================== Greater than (>) ===================================================================
console.log(a > b);                    // false
console.log(b > a);                    // true
console.log();

// ========================================================================================================================================================
// ==================================================================== Less than (<) =====================================================================
console.log(a < b);                    // true
console.log(b < a);                    // false
console.log();