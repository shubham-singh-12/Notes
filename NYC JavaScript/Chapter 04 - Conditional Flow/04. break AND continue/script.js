// =================================================================== BREAK & CONTINUE ===================================================================

// ============================ break =============================
for (let i = 1; i <= 10; i++) {
    if (i === 6) {
        break;
    }
    console.log(i);
}


// =========================== continue ===========================
for (let j = 1; j <= 10; j++) {
    if (j === 6) {
        continue;
    }
    console.log(j);
}
