// =============================== EXAMPLE ================================
public class Arithmetic_Operators {
    static void main() {

        int a = 25;
        int b = 7;

        System.out.println(a + b);          // 32
        System.out.println(a - b);          // 18
        System.out.println(a * b);          // 175
        System.out.println(a / b);          // 3
        System.out.println(a % b);          // 4
    }
}