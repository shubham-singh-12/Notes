public class Relational_Operators {
    static void main() {

        int currentStreak = 45;
        int targetStreak = 50;

        System.out.println(currentStreak == targetStreak);      // false
        System.out.println(currentStreak != targetStreak);      // true
        System.out.println(currentStreak > targetStreak);       // false
        System.out.println(currentStreak < targetStreak);       // false
        System.out.println(currentStreak >= targetStreak);      // false
        System.out.println(currentStreak <= targetStreak);      // true
    }
}