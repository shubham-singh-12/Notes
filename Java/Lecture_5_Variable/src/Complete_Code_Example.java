public class Complete_Code_Example {
    public static void main(String[] args) {

//        Declaration + Initialization
        int age = 5;
        System.out.println(age);

//        Update value
        age = 11;
        System.out.println(age);

//        Meaningful names
        int totalMarks = 20;
        System.out.println(totalMarks);         // OUTPUT: 20

//        Case sensitivity
        int weight = 80;
        int Weight = 90;
        System.out.println(weight);             // OUTPUT: 80
        System.out.println(Weight);             // OUTPUT: 90

//        camelCase
        int myAge = 21;
        String myNameIsShubham = "Shubham";

//        Constant - ALL_CAPS
        int DAYS_IN_A_YEAR = 365;
        System.out.println(DAYS_IN_A_YEAR);;    // OUTPUT: 365
    }
}
